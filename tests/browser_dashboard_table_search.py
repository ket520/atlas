from playwright.sync_api import sync_playwright, expect
from browser_responsive_tables import serve
with sync_playwright() as pw:
    browser=pw.chromium.launch()
    page=browser.new_page(viewport={'width':1440,'height':900},reduced_motion='reduce')
    page.add_init_script("sessionStorage.setItem('deliverydesk-started','1');localStorage.setItem('deliverydesk-dashboard-widgets-v1',JSON.stringify(['cancelled','hold']));localStorage.setItem('deliverydesk-dashboard-widgets-v1-sizes',JSON.stringify({'cancelled':'1x3','cancelled-slot':0,'hold':'1x3','hold-slot':1}))")
    page.route('https://deliverydesk.test/**',serve)
    page.route('https://fonts.googleapis.com/**',lambda route:route.abort())
    page.goto('https://deliverydesk.test/pages/dashboard.html')
    page.evaluate("""() => {const date=new Intl.DateTimeFormat('en-CA',{timeZone:'Europe/London',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());const rows=['Cancelled','On Hold'].flatMap((carrier,c)=>Array.from({length:3},(_,i)=>({id:carrier+i,order:String(65000+c*10+i),orderRef:'REF-'+(65000+c*10+i),carrier,st:c?'Unassigned':'Cancelled',orderDate:date,cust:'Example',logs:[]})));DeliveryStore.hydrate({deliveries:rows,activity:[],integrations:[]});D=DeliveryStore.deliveries();R();}""")
    for key in ['cancelled','hold']:
        card=page.locator(f'[data-dash-widget="{key}"]')
        card.locator('[data-table-search-open]').click()
        search=card.locator('[data-table-order-search]')
        expect(search).to_be_focused()
        expect(card.locator('[data-table-search-close]')).to_have_count(0)
        assert search.evaluate('(el)=>Math.abs(el.getBoundingClientRect().width-el.parentElement.getBoundingClientRect().width)<1')
        query='65001' if key=='cancelled' else '65011'
        search.fill(query)
        expect(card.locator('tbody tr')).to_have_count(1)
        expect(card.locator('tbody [data-dash-order]')).to_have_text(query)
        expect(search).to_be_focused()
        search.fill('missing')
        expect(card.locator('tbody')).to_have_text('No matching order IDs')
        search.press('Escape')
        expect(card.locator('[data-table-search-open]')).to_be_visible()
        expect(card.locator('tbody tr')).to_have_count(3)
        card.locator('[data-table-search-open]').click()
        card.locator('[data-table-order-search]').fill(query)
        page.locator('.dash-workspace-heading h1').click()
        expect(card.locator('[data-table-order-search]')).to_have_count(0)
        expect(card.locator('[data-table-search-open]')).to_be_visible()
        expect(card.locator('tbody tr')).to_have_count(3)
    browser.close()
    print('PASS: all tall table types open inline Order search, filter IDs, retain focus, show empty results, and clear/close with Escape')
