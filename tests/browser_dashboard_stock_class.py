from playwright.sync_api import sync_playwright, expect
from browser_responsive_tables import serve
with sync_playwright() as pw:
    browser=pw.chromium.launch()
    page=browser.new_page(viewport={'width':1440,'height':900},reduced_motion='reduce')
    page.add_init_script("sessionStorage.setItem('deliverydesk-started','1');localStorage.setItem('deliverydesk-dashboard-widgets-v1',JSON.stringify(['palletways-unbooked','palletways-unbooked--1x3']));localStorage.setItem('deliverydesk-dashboard-widgets-v1-sizes',JSON.stringify({'palletways-unbooked-slot':0,'palletways-unbooked--1x3':'1x3','palletways-unbooked--1x3-slot':1}))")
    page.route('https://deliverydesk.test/**',serve)
    page.route('https://fonts.googleapis.com/**',lambda route:route.abort())
    page.goto('https://deliverydesk.test/pages/dashboard.html')
    page.evaluate("""() => {const rows=[['Palletways','B2C'],['Palletways','B2B'],['Palletways','B2B'],['Palletways',''],['Own van','B2C']].map(([carrier,classification],i)=>({id:'s'+i,order:'6500'+i,carrier,st:'Scheduled',bookingStatus:'Out of Stock',salesActivityPresent:true,palletwaysSheetBookedIn:'No',palletwaysDetails:{classification},logs:[]}));DeliveryStore.hydrate({deliveries:rows,activity:[],integrations:[]});D=DeliveryStore.deliveries();R();}""")
    small=page.locator('[data-dash-widget="palletways-unbooked"]')
    tall=page.locator('[data-dash-widget="palletways-unbooked--1x3"]')
    expect(small.locator('.dash-widget-total')).to_have_text('1')
    expect(tall.locator('tbody tr')).to_have_count(1)
    expect(tall.locator('thead th')).to_have_count(4)
    expect(tall.locator('.dash-widget-foot [data-unbooked-class]')).to_have_count(2)
    expect(tall.locator('.dash-widget-head [data-unbooked-class]')).to_have_count(0)
    tall.locator('[data-unbooked-class="B2B"]').click()
    expect(tall.locator('tbody tr')).to_have_count(2)
    expect(tall.locator('.dash-table-record-total')).to_have_text('2 records')
    expect(small.locator('.dash-widget-total')).to_have_text('1')
    small.locator('[data-unbooked-class="B2B"]').click()
    expect(small.locator('.dash-widget-total')).to_have_text('2')
    expect(small.locator('[data-dash-view]')).to_have_attribute('data-dash-view','palletways-unbooked-b2b')
    assert page.evaluate("JSON.parse(localStorage.getItem('deliverydesk-dashboard-widgets-v1-sizes'))['palletways-unbooked--1x3-class']==='B2B'")
    # Hiding B2B must override saved B2B selections in both widget sizes.
    page.evaluate("go('Settings')")
    page.locator('[data-settings-company="palletways-b2b"]').check()
    page.evaluate("go('Dashboard')")
    expect(page.locator('[data-unbooked-class]')).to_have_count(0)
    expect(small.locator('.dash-unbooked-class-label')).to_have_text('B2C')
    expect(small.locator('.dash-widget-total')).to_have_text('1')
    expect(tall.locator('tbody tr')).to_have_count(1)
    for card in (small, tall):
        expect(card.locator('[data-dash-view]')).to_have_attribute('data-dash-view','palletways-unbooked-b2c')
        assert 'B2B' not in card.inner_text()
    page.evaluate("go('Settings')")
    page.locator('[data-settings-company="palletways-b2b"]').uncheck()
    page.evaluate("go('Dashboard')")
    expect(small.locator('[data-unbooked-class]')).to_have_count(2)
    expect(tall.locator('[data-unbooked-class]')).to_have_count(2)
    browser.close()
    print('PASS: explicit Palletways B2C/B2B only,  switch positions, independent sizes, counts, and saved choices')
